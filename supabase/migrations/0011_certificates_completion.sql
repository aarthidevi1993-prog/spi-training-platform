-- ===================================================================
-- 0011 — COMPLETION MANAGEMENT AND CERTIFICATES
--
-- Batch completion requirements, server-side eligibility, the
-- recommendation → approval → certificate workflow, revocation /
-- reissue, and public verification.
--
--   batch_final_assessments (batch_id)                          PK
--     batch_id                  → batches (id)
--     (test_id, batch_id)       → tests (id, batch_id)            [0008 key]
--   batch_required_assignments (batch_id, assignment_id)        PK
--     batch_id                  → batches (id)
--     (assignment_id, batch_id) → class_assignments (id, batch_id) [0006 key]
--   completion_records (id)                                     PK
--     (batch_id, student_id)    → batch_students (batch_id, student_id)
--     unique (batch_id, student_id), unique (id, batch_id, student_id)
--   certificates (id)                                           PK
--     (completion_id, batch_id, student_id) → completion_records
--     (batch_id, student_id)    → batch_students
--     replaces_certificate_id   → certificates (id)
--     unique certificate_number, unique replaces_certificate_id,
--     partial unique (batch_id, student_id) WHERE status = 'issued'
--   completion_events (id)                                      PK (append-only)
--   certificate_number_counters (year)                          PK (no user access)
--
-- RULES
--   * Eligibility is calculated from live data by the database
--     (completion_eligibility) and re-checked at recommendation,
--     approval and issue; the result is frozen as evidence on the
--     completion record. The browser never declares eligibility.
--   * Requirements (final assessment + required assignments) can only
--     change while the batch is upcoming/ongoing AND no completion of
--     the batch is approved. Enforced in the functions AND in guard
--     triggers (insert/update/delete, every writer).
--   * Completion and certification are separate from
--     batch_students.enrollment_status, which 0011 never changes.
--   * Certificates are immutable snapshots. Number, verification code,
--     snapshot and hash are generated by the database (the guard
--     trigger ignores any supplied values). Only issued → revoked is
--     allowed; reissue creates a new certificate that references the
--     revoked one. Nothing is ever deleted.
--   * Every write requires a signed-in user (auth.uid()) and the right
--     role — also for the service role and the SQL Editor — and stamps
--     the actor. All events are written by AFTER triggers, so every
--     change is audited whichever path made it.
--
-- ACCESS: nobody gets INSERT/UPDATE/DELETE privileges. Staff read via
-- RLS (super admin: all; the batch's assigned trainer:
-- is_batch_trainer). Students have no table access — they use
-- student_completion_status() / student_certificates(). Anonymous
-- users can only call verify_certificate(number, code).
--
-- LOCKING: every completion operation on a batch takes a per-batch
-- transaction advisory lock (completion_batch_lock) plus FOR SHARE on
-- the batch (and enrolment) row, so requirement changes, approvals and
-- issues on one batch are serialised and a concurrent batch status
-- change waits for them.
--
-- 0011 does NOT modify any existing table, function, policy or
-- migration. Runs as ONE transaction — paste into the SQL Editor as-is.
-- Depends on 0001–0010. REVIEW BEFORE RUNNING.
-- ===================================================================

begin;

