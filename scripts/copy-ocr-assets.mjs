// Copies the self-hosted OCR files (Phase H) from node_modules into public/ocr/,
// so the browser never fetches OCR code or language data from a CDN.
//   node scripts/copy-ocr-assets.mjs          copy + write public/ocr/manifest.json
//   node scripts/copy-ocr-assets.mjs --check  verify public/ocr matches node_modules (exit 1 if not)
// Run it again after upgrading tesseract.js, tesseract.js-core, @tesseract.js-data/eng or pdfjs-dist.
import { createHash } from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const nm = (p) => path.join(root, "node_modules", p);
const out = path.join(root, "public", "ocr");
const version = (pkg) => JSON.parse(fs.readFileSync(nm(`${pkg}/package.json`), "utf8")).version;

/** [source in node_modules, destination under public/ocr] */
const FILES = [
  ["tesseract.js/dist/worker.min.js", "worker.min.js"],
  ["tesseract.js/LICENSE.md", "LICENSE-tesseract.js.md"],
  // LSTM-only engines (OEM 1); tesseract.js picks relaxed-SIMD, SIMD or plain by browser support.
  ["tesseract.js-core/tesseract-core-relaxedsimd-lstm.wasm.js", "core/tesseract-core-relaxedsimd-lstm.wasm.js"],
  ["tesseract.js-core/tesseract-core-simd-lstm.wasm.js", "core/tesseract-core-simd-lstm.wasm.js"],
  ["tesseract.js-core/tesseract-core-lstm.wasm.js", "core/tesseract-core-lstm.wasm.js"],
  ["tesseract.js-core/LICENSE", "LICENSE-tesseract.js-core"],
  // English, integer-quantised LSTM model (smaller and faster; used with OEM 1).
  ["@tesseract.js-data/eng/4.0.0_best_int/eng.traineddata.gz", "lang/eng.traineddata.gz"],
  // pdf.js image decoders for scanned pages (JPEG 2000, JBIG2) and colour management.
  ["pdfjs-dist/wasm/openjpeg.wasm", "pdfjs/openjpeg.wasm"],
  ["pdfjs-dist/wasm/jbig2.wasm", "pdfjs/jbig2.wasm"],
  ["pdfjs-dist/wasm/qcms_bg.wasm", "pdfjs/qcms_bg.wasm"],
  ["pdfjs-dist/wasm/LICENSE_OPENJPEG", "pdfjs/LICENSE_OPENJPEG"],
  ["pdfjs-dist/wasm/LICENSE_JBIG2", "pdfjs/LICENSE_JBIG2"],
  ["pdfjs-dist/wasm/LICENSE_QCMS", "pdfjs/LICENSE_QCMS"],
];

const sha256 = (file) => createHash("sha256").update(fs.readFileSync(file)).digest("hex");
const manifest = {
  note: "Generated by scripts/copy-ocr-assets.mjs — do not edit.",
  packages: { "tesseract.js": version("tesseract.js"), "tesseract.js-core": version("tesseract.js-core"), "@tesseract.js-data/eng": version("@tesseract.js-data/eng"), "pdfjs-dist": version("pdfjs-dist") },
  files: Object.fromEntries(FILES.map(([src, dest]) => [dest, sha256(nm(src))])),
};

if (process.argv.includes("--check")) {
  const problems = [];
  let current = null;
  try {
    current = JSON.parse(fs.readFileSync(path.join(out, "manifest.json"), "utf8"));
  } catch {
    problems.push("public/ocr/manifest.json is missing");
  }
  for (const [, dest] of FILES) {
    const file = path.join(out, dest);
    if (!fs.existsSync(file)) problems.push(`missing public/ocr/${dest}`);
    else if (sha256(file) !== manifest.files[dest]) problems.push(`public/ocr/${dest} differs from node_modules`);
  }
  if (current && JSON.stringify(current.packages) !== JSON.stringify(manifest.packages)) problems.push("manifest package versions differ from node_modules");
  if (problems.length) {
    console.error(problems.join("\n") + "\nRun: node scripts/copy-ocr-assets.mjs");
    process.exit(1);
  }
  console.log("public/ocr matches node_modules");
} else {
  for (const [src, dest] of FILES) {
    fs.mkdirSync(path.dirname(path.join(out, dest)), { recursive: true });
    fs.copyFileSync(nm(src), path.join(out, dest));
  }
  fs.writeFileSync(path.join(out, "manifest.json"), JSON.stringify(manifest, null, 2) + "\n");
  const bytes = FILES.reduce((s, [, dest]) => s + fs.statSync(path.join(out, dest)).size, 0);
  console.log(`copied ${FILES.length} files (${(bytes / 1024 / 1024).toFixed(1)} MB) to public/ocr`);
}
