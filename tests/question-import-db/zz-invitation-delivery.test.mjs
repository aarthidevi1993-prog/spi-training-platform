async function call(client, fn, args = {}) {
  const { data, error } = await client.rpc(fn, args);
  if (error) throw new Error(`${fn}: ${error.code} ${error.message}`);
  return data;
}
async function err(client, fn, args = {}) {
  const { error } = await client.rpc(fn, args);
  return error;
}
