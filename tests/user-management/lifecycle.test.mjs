const { createUsersService, UsersAuthorizationError, UsersActionError } = await import(`${build}/services/users.service.core.mjs`);
const { UsersFunctionError } = await import(`${build}/repositories/users.repository.core.mjs`);

const ID = "11111111-1111-4111-8111-111111111111";
const ADMIN_ID = "22222222-2222-4222-8222-222222222222";
const ADMIN = { id: ADMIN_ID, email: "a@test", fullName: "A", role: "admin", isActive: true, createdAt: "2026-01-01" };

function record(over = {}) {
  return {
    id: ID,
    role: "student",
    account_status: "active",
    account_status_changed_at: "2026-09-01T10:00:00+00:00",
    created_at: "2026-08-01T10:00:00+00:00",
    updated_at: "2026-09-01T10:00:00+00:00",
    students: {
      student_code: "S1",
      full_name: "Asha Rao",
      status: "active",
      student_details: { email: "asha@example.test", phone: "123", organization: "Org", designation: null },
      batch_students: [],
    },
    trainers: null,
    ...over,
  };
}

// ---------------------------------------------------------------- validation
test("ids, statuses and roles: only whitelisted values pass", () => {
  assert.equal(L.isUuid(ID), true);
  for (const bad of ["", "x", `${ID} `, "11111111111141118111111111111111", null, 5, {}]) assert.equal(L.isUuid(bad), false, String(bad));
  assert.deepEqual(L.parseTargetStatus("suspended"), { ok: true, value: "suspended" });
  assert.deepEqual(L.parseTargetStatus("active"), { ok: true, value: "active" });
  for (const bad of ["invited", "deleted", "SUSPENDED", "", null, ["active"]]) assert.equal(L.parseTargetStatus(bad).ok, false, String(bad));
  assert.deepEqual(L.parseTargetRole("admin"), { ok: true, value: "super_admin" });
  assert.deepEqual(L.parseTargetRole("trainer"), { ok: true, value: "trainer" });
  assert.deepEqual(L.parseTargetRole("student"), { ok: true, value: "student" });
  for (const bad of ["super_admin", "owner", "Admin", "constructor", "__proto__", "toString", "", null, 1]) assert.equal(L.parseTargetRole(bad).ok, false, String(bad));
});

test("reason: trimmed, blank → null, capped at 500", () => {
  assert.deepEqual(L.normalizeReason("  policy breach  "), { ok: true, value: "policy breach" });
  assert.deepEqual(L.normalizeReason("   "), { ok: true, value: null });
  assert.deepEqual(L.normalizeReason(undefined), { ok: true, value: null });
  assert.equal(L.normalizeReason("x".repeat(501)).ok, false);
  assert.equal(L.normalizeReason({ a: 1 }).ok, false);
});

test("role details: a new record needs only a full name; a code is never sent (generated by the database); otherwise nothing is sent", () => {
  assert.deepEqual(L.buildRoleDetails("super_admin", true, { fullName: "Y" }), { ok: true, value: {} });
  assert.deepEqual(L.buildRoleDetails("trainer", false, { fullName: "Y" }), { ok: true, value: {} }, "existing record is reactivated by the DB");
  assert.deepEqual(L.buildRoleDetails("trainer", true, { fullName: " Tara " }), { ok: true, value: { full_name: "Tara" } });
  assert.deepEqual(L.buildRoleDetails("student", true, { code: "FORGED", student_code: "FORGED", fullName: "Sam" }), { ok: true, value: { full_name: "Sam" } }, "a supplied code is dropped");
  for (const input of [{ fullName: " " }, { fullName: "" }, null, { fullName: 5 }, { fullName: "x".repeat(201) }]) {
    assert.equal(L.buildRoleDetails("student", true, input).ok, false, JSON.stringify(input));
  }
});

const studentContact = { kind: "student", fields: { fullName: "Asha Rao", phone: "123", organization: "Org", designation: null } };
const trainerContact = { kind: "trainer", fields: { fullName: "Tara", phone: null, organization: null, designation: null, specializations: ["PLC", "DCS"], bio: null } };

test("details patch: only changed fields (an unchanged form writes and audits nothing)", () => {
  assert.deepEqual(L.buildDetailsPatch(studentContact, { fullName: "Asha Rao", phone: "123", organization: "Org", designation: "" }), { ok: true, value: {} });
  assert.deepEqual(L.buildDetailsPatch(studentContact, { fullName: " Asha  Rao ", phone: "", organization: "Org", designation: "Engineer" }), {
    ok: true,
    value: { full_name: "Asha  Rao", phone: null, designation: "Engineer" },
  });
  assert.deepEqual(L.buildDetailsPatch(trainerContact, { fullName: "Tara", phone: "", bio: "", specializations: ["PLC", "DCS", "PLC", " "] }), { ok: true, value: {} });
  assert.deepEqual(L.buildDetailsPatch(trainerContact, { fullName: "Tara", specializations: ["SCADA"], bio: "Hi" }), { ok: true, value: { bio: "Hi", specializations: ["SCADA"] } });
  // Fields of the other kind are ignored (never sent to the other function).
  assert.deepEqual(L.buildDetailsPatch(studentContact, { fullName: "Asha Rao", phone: "123", organization: "Org", bio: "x", specializations: ["y"], role: "admin" }), { ok: true, value: {} });
});

test("details patch: required name, length caps and list shape are enforced", () => {
  assert.equal(L.buildDetailsPatch(studentContact, { fullName: "" }).ok, false);
  assert.equal(L.buildDetailsPatch(studentContact, { fullName: "x".repeat(201) }).ok, false);
  assert.equal(L.buildDetailsPatch(studentContact, { fullName: "A", phone: "1".repeat(41) }).ok, false);
  assert.equal(L.buildDetailsPatch(studentContact, { fullName: "A", organization: "o".repeat(201) }).ok, false);
  assert.equal(L.buildDetailsPatch(trainerContact, { fullName: "A", bio: "b".repeat(2001) }).ok, false);
});

test("details patch: trainer organization/designation (0022) — same rules as the student's", () => {
  // Set: trimmed, sent with the 0022 function keys.
  assert.deepEqual(L.buildDetailsPatch(trainerContact, { fullName: "Tara", organization: "  Acme Corp ", designation: "Lead Trainer" }), { ok: true, value: { organization: "Acme Corp", designation: "Lead Trainer" } });
  // Unchanged: nothing sent, nothing audited.
  const filled = { kind: "trainer", fields: { ...trainerContact.fields, organization: "Acme", designation: "Lead" } };
  assert.deepEqual(L.buildDetailsPatch(filled, { fullName: "Tara", organization: "Acme", designation: "Lead", specializations: ["PLC", "DCS"] }), { ok: true, value: {} });
  // Blank → null (cleared).
  assert.deepEqual(L.buildDetailsPatch(filled, { fullName: "Tara", organization: "   ", designation: "" }), { ok: true, value: { organization: null, designation: null } });
  // 200 is allowed; over 200 is refused.
  assert.equal(L.buildDetailsPatch(trainerContact, { fullName: "Tara", organization: "o".repeat(200) }).ok, true);
  assert.equal(L.buildDetailsPatch(trainerContact, { fullName: "Tara", organization: "o".repeat(201) }).ok, false);
  assert.equal(L.buildDetailsPatch(trainerContact, { fullName: "Tara", designation: "d".repeat(201) }).ok, false);
  // Students unchanged; a student form still never sends trainer-only fields.
  assert.deepEqual(L.buildDetailsPatch(studentContact, { fullName: "Asha Rao", phone: "123", organization: "Org", designation: "Eng", bio: "x", specializations: ["y"] }), { ok: true, value: { designation: "Eng" } });
  assert.equal(L.buildDetailsPatch(trainerContact, { fullName: "A", specializations: "PLC" }).ok, false);
  assert.equal(L.buildDetailsPatch(trainerContact, { fullName: "A", specializations: Array.from({ length: 21 }, (_, i) => `s${i}`) }).ok, false);
  assert.equal(L.buildDetailsPatch(trainerContact, { fullName: "A", specializations: ["x".repeat(101)] }).ok, false);
  assert.equal(L.buildDetailsPatch(studentContact, { fullName: 42 }).ok, false);
});

