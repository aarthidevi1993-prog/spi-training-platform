create function public.add_required_assignment(p_batch_id uuid, p_assignment_id uuid)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_reason  text;
  a         record;
begin
  perform public.require_completion_admin();
  if p_batch_id is null or p_assignment_id is null then
    raise exception 'A batch and an assignment are required.' using errcode = '22023';
  end if;

  perform public.completion_batch_lock(p_batch_id);
  perform 1 from public.batches b where b.id = p_batch_id for share;
  v_reason := public.completion_requirements_lock_reason(p_batch_id);
  if v_reason = 'batch_not_found' then
    return jsonb_build_object('ok', false, 'reason', 'not_found');
  elsif v_reason is not null then
    return jsonb_build_object('ok', false, 'reason', 'requirements_locked', 'lock_reason', v_reason);
  end if;

  select ca.batch_id, ca.status, c.status as class_status
    into a
    from public.class_assignments ca join public.classes c on c.id = ca.class_id
   where ca.id = p_assignment_id;
  if not found or a.batch_id <> p_batch_id then
    return jsonb_build_object('ok', false, 'reason', 'assignment_not_in_batch');
  elsif a.status not in ('published', 'closed') then
    return jsonb_build_object('ok', false, 'reason', 'assignment_draft');
  elsif a.class_status = 'cancelled' then
    return jsonb_build_object('ok', false, 'reason', 'class_cancelled');
  end if;

  if exists (select 1 from public.batch_required_assignments ra
              where ra.batch_id = p_batch_id and ra.assignment_id = p_assignment_id) then
    return jsonb_build_object('ok', false, 'reason', 'already_required');
  end if;
  insert into public.batch_required_assignments (batch_id, assignment_id) values (p_batch_id, p_assignment_id);
  return jsonb_build_object('ok', true, 'changed', true);
end;
$$;

