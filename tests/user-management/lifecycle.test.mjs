test("action hints: never on your own account; follow the database's transitions; the last-Super-Admin rule is left to the database", () => {
  const detail = (over, viewer = ADMIN_ID) => L.mapUserDetail(record(over), [], viewer);
  const active = detail({});
  assert.deepEqual([active.actions.suspend, active.actions.reactivate, active.actions.changeRole, active.actions.editDetails], [true, false, true, true]);
  const suspended = detail({ account_status: "suspended" });
  assert.deepEqual([suspended.actions.suspend, suspended.actions.reactivate, suspended.actions.changeRole], [false, true, false]);
  const invited = detail({ account_status: "invited", students: null });
  // 0018: an invited account is neither suspended nor activated here — only invitation acceptance changes it.
  assert.deepEqual([invited.actions.suspend, invited.actions.reactivate, invited.actions.changeRole, invited.actions.editDetails], [false, false, false, false]);
  assert.match(invited.actions.note, /accept/i);
  const self = detail({ role: "super_admin", students: null, id: ADMIN_ID });
  assert.equal(self.isSelf, true);
  assert.deepEqual([self.actions.suspend, self.actions.reactivate, self.actions.changeRole], [false, false, false]);
  assert.match(self.actions.note, /your own account/);
  // Another Super Admin: offered — whether it is the last one is decided only by the database.
  const otherAdmin = detail({ role: "super_admin", students: null });
  assert.deepEqual([otherAdmin.actions.suspend, otherAdmin.actions.changeRole], [true, true]);
  // Records: the trainer's student record (old role) is not editable here; contact comes from the current role only.
  const rc = detail({ role: "trainer", trainers: { trainer_code: "T1", full_name: "Tara", status: "active", trainer_details: [{ email: "t@x", phone: null, specializations: null, bio: "b" }], batches: [] } });
  assert.deepEqual(rc.contact, { kind: "trainer", fields: { fullName: "Tara", phone: null, organization: null, designation: null, specializations: [], bio: "b" } });
  const withOrg = detail({ role: "trainer", trainers: { trainer_code: "T1", full_name: "Tara", status: "active", trainer_details: [{ email: "t@x", phone: null, organization: "Acme", designation: "Lead", specializations: ["PLC"], bio: null }], batches: [] } });
  assert.deepEqual([withOrg.contact.fields.organization, withOrg.contact.fields.designation], ["Acme", "Lead"], "trainer organization/designation read from trainer_details (0022)");
  assert.equal(rc.hasStudentRecord, true);
  assert.equal(rc.hasTrainerRecord, true);
});

// ---------------------------------------------------------------- service
function fakeRepo(over = {}) {
  const calls = [];
  const ok = async () => ({ ok: true, reason: null });
  const repository = {
    listProfiles: async () => [],
    getProfile: async (id) => (calls.push(["getProfile", id]), record()),
    listAuditEvents: async () => [],
    latestStatusChange: async () => null,
    setAccountStatus: async (...a) => (calls.push(["setAccountStatus", ...a]), (over.setAccountStatus ?? ok)(...a)),
    setUserRole: async (...a) => (calls.push(["setUserRole", ...a]), (over.setUserRole ?? ok)(...a)),
    updateStudent: async (...a) => (calls.push(["updateStudent", ...a]), (over.updateStudent ?? ok)(...a)),
    updateTrainer: async (...a) => (calls.push(["updateTrainer", ...a]), (over.updateTrainer ?? ok)(...a)),
    ...(over.getProfile ? { getProfile: over.getProfile } : {}),
  };
  return { calls, repository };
}
const svcFor = (user, over, extra = {}) => {
  const f = fakeRepo(over);
  return { ...f, svc: createUsersService({ repository: f.repository, getCurrentUser: async () => user, ...extra }) };
};

test("service: signed-out, trainer and student callers are refused before any request", async () => {
  for (const user of [null, { ...ADMIN, role: "trainer" }, { ...ADMIN, role: "student" }]) {
    const { svc, calls } = svcFor(user);
    await assert.rejects(svc.setAccountStatus(ID, "suspended", null), UsersAuthorizationError);
    await assert.rejects(svc.changeRole(ID, "admin", null), UsersAuthorizationError);
    await assert.rejects(svc.updateDetails(ID, { fullName: "X" }), UsersAuthorizationError);
    await assert.rejects(svc.getUserDetail(ID), UsersAuthorizationError);
    assert.deepEqual(calls, [], `${user?.role ?? "anonymous"}: nothing reached the repository`);
  }
});

test("service: invalid ids, statuses, roles and reasons are refused before any request", async () => {
  const { svc, calls } = svcFor(ADMIN);
  await assert.rejects(svc.setAccountStatus("not-a-uuid", "suspended", null), UsersActionError);
  await assert.rejects(svc.setAccountStatus(ID, "invited", null), UsersActionError);
  await assert.rejects(svc.setAccountStatus(ID, "suspended", "x".repeat(501)), UsersActionError);
  await assert.rejects(svc.changeRole(ID, "super_admin", null), UsersActionError, "database role names are not accepted from the browser");
  await assert.rejects(svc.changeRole(ID, "owner", null), UsersActionError);
  await assert.rejects(svc.updateDetails("x", { fullName: "A" }), UsersActionError);
  assert.deepEqual(calls, []);
  assert.equal(await svc.getUserDetail("not-a-uuid"), null);
});

test("service: outcomes become safe messages; raised database errors map by SQLSTATE only", async () => {
  const refuse = (reason) => async () => ({ ok: false, reason });
  let s = svcFor(ADMIN, { setAccountStatus: refuse("last_super_admin") }).svc;
  await assert.rejects(s.setAccountStatus(ID, "suspended", null), (e) => e instanceof UsersActionError && e.message === L.STATUS_REASON_MESSAGE.last_super_admin);
  s = svcFor(ADMIN, { setAccountStatus: refuse("cannot_change_self") }).svc;
  await assert.rejects(s.setAccountStatus(ID, "suspended", null), (e) => e.message === L.STATUS_REASON_MESSAGE.cannot_change_self);
  s = svcFor(ADMIN, { setAccountStatus: async () => { throw new UsersFunctionError("42501"); } }).svc;
  await assert.rejects(s.setAccountStatus(ID, "active", null), (e) => e instanceof UsersActionError && e.message === L.PERMISSION_ERROR);
  s = svcFor(ADMIN, { setUserRole: refuse("has_active_enrollments") }).svc;
  await assert.rejects(s.changeRole(ID, "admin", null), (e) => e.message === L.ROLE_REASON_MESSAGE.has_active_enrollments);
  s = svcFor(ADMIN, { updateStudent: async () => { throw new Error("relation public.x does not exist at character 12"); } }).svc;
  await assert.rejects(s.updateDetails(ID, { fullName: "New Name", phone: "123", organization: "Org" }), (e) => e instanceof UsersActionError && !/relation|public\./.test(e.message));
});

test("service: successful calls send exactly the validated values", async () => {
  const { svc, calls } = svcFor(ADMIN);
  assert.match(await svc.setAccountStatus(ID, "suspended", "  Left  "), /suspended/i);
  assert.deepEqual(calls.at(-1), ["setAccountStatus", ID, "suspended", "Left"]);
  // Student → Trainer: no trainer record exists, so a full name is required; a supplied code is never sent.
  await assert.rejects(svc.changeRole(ID, "trainer", null), UsersActionError);
  assert.match(await svc.changeRole(ID, "trainer", { code: "TR9", fullName: "Asha Rao" }), /Trainer/);
  assert.deepEqual(calls.at(-1), ["setUserRole", ID, "trainer", { full_name: "Asha Rao" }]);
  // The generated code (returned by the database) is reported in the message.
  const withCode = svcFor(ADMIN, { setUserRole: async () => ({ ok: true, reason: null, code: "TRN-00007" }) }).svc;
  assert.equal(await withCode.changeRole(ID, "trainer", { fullName: "Asha Rao" }), "Role changed to Trainer. Trainer code: TRN-00007.");
  // Student → Super Admin: nothing extra is sent.
  await svc.changeRole(ID, "admin", { fullName: "IGNORED" });
  assert.deepEqual(calls.at(-1), ["setUserRole", ID, "super_admin", {}]);
  // Details: only the changed field.
  assert.equal(await svc.updateDetails(ID, { fullName: "Asha Rao", phone: "999", organization: "Org", designation: "" }), "Details saved.");
  assert.deepEqual(calls.at(-1), ["updateStudent", ID, { phone: "999" }]);
  const before = calls.length;
  await assert.rejects(svc.updateDetails(ID, { fullName: "Asha Rao", phone: "123", organization: "Org" }), (e) => e.message === "Nothing changed.");
  assert.equal(calls.filter((c) => c[0] === "updateStudent").length, calls.slice(0, before).filter((c) => c[0] === "updateStudent").length, "no write for an unchanged form");
});

