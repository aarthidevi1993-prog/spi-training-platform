test("every 0017 reason has a safe message; unknown reasons and raised errors never leak detail", () => {
  for (const r of ["cannot_change_self", "not_found", "unchanged", "transition_not_allowed", "never_activated", "last_super_admin"]) assert.ok(L.STATUS_REASON_MESSAGE[r], r);
  for (const r of ["cannot_change_self", "not_found", "account_not_active", "unchanged", "last_super_admin", "has_current_batches", "has_active_enrollments", "has_attempt_in_progress", "details_required", "no_email"]) {
    assert.ok(L.ROLE_REASON_MESSAGE[r], r);
  }
  for (const r of ["not_found", "unchanged", "no_contact_record"]) assert.ok(L.DETAILS_REASON_MESSAGE[r], r);
  assert.equal(L.reasonMessage(L.STATUS_REASON_MESSAGE, "something_new"), L.GENERIC_ACTION_ERROR);
  assert.equal(L.reasonMessage(L.STATUS_REASON_MESSAGE, "__proto__"), L.GENERIC_ACTION_ERROR);
  assert.equal(L.reasonMessage(L.STATUS_REASON_MESSAGE, null), L.GENERIC_ACTION_ERROR);
  assert.equal(L.errorCodeMessage("42501"), L.PERMISSION_ERROR);
  assert.equal(L.errorCodeMessage("22023"), L.INVALID_VALUES_ERROR);
  assert.equal(L.errorCodeMessage("XX000"), L.GENERIC_ACTION_ERROR);
  const all = [...Object.values(L.STATUS_REASON_MESSAGE), ...Object.values(L.ROLE_REASON_MESSAGE), ...Object.values(L.DETAILS_REASON_MESSAGE)].join(" ");
  assert.doesNotMatch(all, /public\.|SQLSTATE|ERROR:|profiles\.|_fkey|super_admin|42501/);
});

