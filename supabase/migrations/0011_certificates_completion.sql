-- Recommend (or re-recommend after rejection/withdrawal). Super admin or
-- the batch's assigned trainer. Refused unless eligible now.
create function public.recommend_completion(p_batch_id uuid, p_student_id uuid, p_note text default null)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_note  text := nullif(btrim(coalesce(p_note, '')), '');
  v_elig  jsonb;
  r       record;
  v_id    uuid;
begin
  if auth.uid() is null
     or p_batch_id is null
     or not (public.is_super_admin() or public.is_batch_trainer(p_batch_id)) then
    raise exception 'You can only recommend completion for batches you are assigned to.' using errcode = '42501';
  end if;
  if p_student_id is null then
    raise exception 'A student is required.' using errcode = '22023';
  end if;
  if v_note is not null and char_length(v_note) > 1000 then
    return jsonb_build_object('ok', false, 'reason', 'note_too_long');
  end if;

  perform public.completion_batch_lock(p_batch_id);
  perform 1 from public.batches b where b.id = p_batch_id for share;
  if not found then
    return jsonb_build_object('ok', false, 'reason', 'not_found');
  end if;
  perform 1 from public.batch_students bs where bs.batch_id = p_batch_id and bs.student_id = p_student_id for share;
  if not found then
    return jsonb_build_object('ok', false, 'reason', 'not_enrolled');
  end if;

  select cr.id, cr.status into r
    from public.completion_records cr
   where cr.batch_id = p_batch_id and cr.student_id = p_student_id
     for update;
  if found and r.status = 'approved' then
    return jsonb_build_object('ok', false, 'reason', 'already_approved');
  elsif found and r.status = 'recommended' then
    return jsonb_build_object('ok', false, 'reason', 'already_recommended');
  end if;

  v_elig := public.completion_eligibility(p_batch_id, p_student_id);
  if (v_elig ->> 'eligible')::boolean is not true then
    return jsonb_build_object('ok', false, 'reason', 'not_eligible', 'eligibility', v_elig);
  end if;

  if r.id is null then
    -- The guard stamps the recommender and recomputes the evidence.
    insert into public.completion_records (batch_id, student_id, status, recommendation_note)
    values (p_batch_id, p_student_id, 'recommended', v_note)
    returning id into v_id;
  else
    update public.completion_records
       set status = 'recommended', recommendation_note = v_note
     where id = r.id
    returning id into v_id;
  end if;
  return jsonb_build_object('ok', true, 'completion_id', v_id, 'status', 'recommended');
end;
$$;

create function public.withdraw_recommendation(p_completion_id uuid)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_batch   uuid;
  v_status  public.completion_status;
begin
  select cr.batch_id into v_batch from public.completion_records cr where cr.id = p_completion_id;
  if auth.uid() is null
     or v_batch is null
     or not (public.is_super_admin() or public.is_batch_trainer(v_batch)) then
