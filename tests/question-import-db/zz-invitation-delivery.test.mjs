test("concurrency: simultaneous attempts are serialised — one is authorized, the other meets the cooldown", async () => {
  const sa = as(W.idv_SA);
  const claims = JSON.stringify({ sub: W.idv_SA });
  const held = (id) =>
    db.run(`begin;\nset local role authenticated;\nselect set_config('request.jwt.claims', '${claims}', true);\nselect public.begin_invitation_delivery('${id}');\nselect pg_sleep(1.5);\ncommit;`);
  const settle = (p) => p.then((v) => v, (e) => e);

  const id = await invite(sa);
  const first = held(id);
  await new Promise((resolve) => setTimeout(resolve, 400));
  const second = settle(begin(sa, id));
  assert.equal((await first).code, 0);
  assert.equal((await second).reason, "cooldown");
  assert.deepEqual([(await inv(id)).resend_count, (await events(id, "invitation_resent")).length], [0, 0]);

  // At the resend cap edge: two concurrent resends cannot both pass (count stays ≤ 5).
  await db.exec(`update public.user_invitations set resend_count = 4, last_sent_at = now() - interval '120 seconds' where id = '${id}';`);
  const r1 = held(id);
  await new Promise((resolve) => setTimeout(resolve, 400));
  const r2 = settle(begin(sa, id));
  assert.equal((await r1).code, 0);
  assert.equal((await r2).reason, "resend_limit", "after waiting for the lock it sees the cap already reached");
  assert.equal((await inv(id)).resend_count, 5);
  assert.equal((await events(id, "invitation_resent")).length, 1);
  await age(id, 61);
  assert.deepEqual(await begin(sa, id), { ok: false, reason: "resend_limit" });
});

