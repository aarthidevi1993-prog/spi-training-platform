returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  t record;
begin
  if auth.uid() is null or not public.is_super_admin() then
    raise exception 'Completion requirements can only be changed by a signed-in Super Admin.' using errcode = '42501';
  end if;
  if tg_op = 'UPDATE' and new.batch_id is distinct from old.batch_id then
    raise exception 'A final assessment cannot be moved to another batch.' using errcode = '42501';
  end if;

  perform public.completion_requirements_assert_unlocked(case when tg_op = 'DELETE' then old.batch_id else new.batch_id end);

  if tg_op = 'DELETE' then
    return old;
  end if;

  select tt.batch_id, tt.test_type, tt.status, c.status as class_status
    into t
    from public.tests tt
    join public.classes c on c.id = tt.class_id
   where tt.id = new.test_id;
  if not found or t.batch_id <> new.batch_id then
    raise exception 'The final assessment must be a test of this batch.' using errcode = '23514';
  elsif t.test_type <> 'final_exam' then
    raise exception 'The final assessment must be a final exam.' using errcode = '23514';
  elsif t.status = 'draft' then
    raise exception 'The final assessment must be a published test.' using errcode = '23514';
  elsif t.class_status = 'cancelled' then
    raise exception 'The final assessment''s class is cancelled.' using errcode = '23514';
  end if;

  new.designated_by := auth.uid();
  new.designated_at := now();
  return new;
end;
$$;
