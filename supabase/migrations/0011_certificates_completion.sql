-- Staff overview of one batch: requirements, lock state, and every
-- student's eligibility, completion and active certificate.
create function public.staff_batch_completion(p_batch_id uuid)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_batch   record;
  v_reason  text;
begin
  if auth.uid() is null
     or p_batch_id is null
     or not (public.is_super_admin() or public.is_batch_trainer(p_batch_id)) then
    raise exception 'Batch not found, or you don''t have permission to view it.' using errcode = '42501';
  end if;

  select b.id, b.batch_code, b.name, b.status, b.start_date, b.end_date into v_batch
    from public.batches b where b.id = p_batch_id;
  if not found then
    return jsonb_build_object('ok', false, 'reason', 'not_found');
  end if;
  v_reason := public.completion_requirements_lock_reason(p_batch_id);

  return jsonb_build_object(
    'ok', true,
    'batch', jsonb_build_object('id', v_batch.id, 'batch_code', v_batch.batch_code, 'name', v_batch.name,
                                'status', v_batch.status, 'start_date', v_batch.start_date, 'end_date', v_batch.end_date),
    'requirements_locked', v_reason is not null,
    'lock_reason', v_reason,
    'final_assessment', (
      select jsonb_build_object('test_id', t.id, 'title', t.title, 'designated_at', fa.designated_at)
        from public.batch_final_assessments fa join public.tests t on t.id = fa.test_id
       where fa.batch_id = p_batch_id),
    'required_assignments', coalesce((
      select jsonb_agg(jsonb_build_object('assignment_id', ca.id, 'title', ca.title, 'added_at', ra.added_at) order by ca.title)
        from public.batch_required_assignments ra join public.class_assignments ca on ca.id = ra.assignment_id
       where ra.batch_id = p_batch_id), '[]'::jsonb),
    'students', coalesce((
      select jsonb_agg(jsonb_build_object(
               'student_id', s.id,
               'student_code', s.student_code,
               'full_name', s.full_name,
               'enrollment_status', bs.enrollment_status,
               'eligibility', public.completion_eligibility(p_batch_id, s.id),
               'completion', (
                 select jsonb_build_object('id', cr.id, 'status', cr.status, 'recommended_at', cr.recommended_at,
                                           'decided_at', cr.decided_at, 'decision_note', cr.decision_note,
                                           'completion_date', cr.completion_date)
                   from public.completion_records cr
                  where cr.batch_id = p_batch_id and cr.student_id = s.id),
               'active_certificate', (
                 select jsonb_build_object('id', ce.id, 'certificate_number', ce.certificate_number, 'issued_at', ce.issued_at)
                   from public.certificates ce
                  where ce.batch_id = p_batch_id and ce.student_id = s.id and ce.status = 'issued'),
               'revoked_certificates', (
                 select count(*) from public.certificates ce
                  where ce.batch_id = p_batch_id and ce.student_id = s.id and ce.status = 'revoked'))
             order by s.full_name)
        from public.batch_students bs
        join public.students s on s.id = bs.student_id
       where bs.batch_id = p_batch_id
         and (bs.enrollment_status <> 'withdrawn'
              or exists (select 1 from public.completion_records cr where cr.batch_id = p_batch_id and cr.student_id = s.id))), '[]'::jsonb)
  );
end;
$$;

-- The signed-in student's own completion status per enrolment. No
-- internal IDs, staff identities or audit data.
create function public.student_completion_status()
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_uid     uuid := auth.uid();
  v_result  jsonb;
begin
  if v_uid is null or public.current_app_role() is distinct from 'student' then
    raise exception 'Only students can view their completion status.' using errcode = '42501';
  end if;

  select coalesce(jsonb_agg(item order by sort_key desc), '[]'::jsonb) into v_result
    from (
      select b.start_date as sort_key,
             jsonb_build_object(
               'course_code', co.course_code,
               'course_title', co.title,
               'batch_code', b.batch_code,
               'batch_name', b.name,
               'batch_status', b.status,
               'batch_end_date', b.end_date,
               'requirements', jsonb_build_object(
                 'final_assessment', (select t.title from public.batch_final_assessments fa
                                        join public.tests t on t.id = fa.test_id where fa.batch_id = b.id),
                 'required_assignments', coalesce((select jsonb_agg(ca.title order by ca.title)
                                                     from public.batch_required_assignments ra
                                                     join public.class_assignments ca on ca.id = ra.assignment_id
                                                    where ra.batch_id = b.id), '[]'::jsonb)),
               'eligibility', jsonb_build_object(
                 'eligible', (e ->> 'eligible')::boolean,
                 'batch_completed', (e -> 'batch_completed' ->> 'ok')::boolean,
                 'attendance', jsonb_build_object(
                   'ok', (e -> 'attendance' ->> 'ok')::boolean,
                   'attended', e -> 'attendance' -> 'attended',
                   'eligible_classes', e -> 'attendance' -> 'eligible_classes',
                   'percent', e -> 'attendance' -> 'percent',
                   'minimum_percent', 75),
                 'final_assessment', jsonb_build_object(
                   'ok', (e -> 'final_assessment' ->> 'ok')::boolean,
                   'state', e -> 'final_assessment' ->> 'state'),
                 'assignments', jsonb_build_object(
                   'ok', (e -> 'assignments' ->> 'ok')::boolean,
                   'required', e -> 'assignments' -> 'required',
                   'satisfied', e -> 'assignments' -> 'satisfied')),
               'completion', case when cr.id is null then null else jsonb_build_object(
                 'status', cr.status,
                 'completion_date', cr.completion_date,
                 'rejection_note', case when cr.status = 'rejected' then cr.decision_note end,
                 'may_become_eligible', cr.status in ('rejected', 'withdrawn')) end
             ) as item
        from public.batch_students bs
        join public.batches b on b.id = bs.batch_id
        join public.courses co on co.id = b.course_id
        left join public.completion_records cr on cr.batch_id = bs.batch_id and cr.student_id = bs.student_id
        cross join lateral (select public.completion_eligibility(bs.batch_id, bs.student_id) as e) el
       where bs.student_id = v_uid
         and bs.enrollment_status in ('enrolled', 'completed')
    ) x;
  return v_result;
end;
$$;

