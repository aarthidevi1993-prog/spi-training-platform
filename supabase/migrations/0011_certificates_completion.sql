-- Public verification: BOTH the number and the verification code must
-- match exactly. Any other input gets the identical {found:false}.
create function public.verify_certificate(p_number text, p_code text)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_number  text := upper(btrim(coalesce(p_number, '')));
  v_code    text := upper(btrim(coalesce(p_code, '')));
  ce        record;
begin
  if v_number !~ '^ARS-SPI-[0-9]{4}-[0-9]{6}$' or v_code !~ '^[0-9A-F]{20}$' then
    return jsonb_build_object('found', false);
  end if;

  select c.certificate_number, c.student_name, c.course_code, c.course_title, c.batch_code, c.batch_name,
         c.completion_date, c.issued_at, c.status, c.revoked_at
    into ce
    from public.certificates c
   where c.certificate_number = v_number and c.verification_code = v_code;
  if not found then
    return jsonb_build_object('found', false);
  end if;

  return jsonb_build_object(
    'found', true,
    'certificate_number', ce.certificate_number,
    'student_name', ce.student_name,
    'course_code', ce.course_code,
    'course_title', ce.course_title,
    'batch_code', ce.batch_code,
    'batch_name', ce.batch_name,
    'completion_date', ce.completion_date,
    'issue_date', (ce.issued_at at time zone 'Asia/Kolkata')::date,
    'status', ce.status,
    'revoked_date', case when ce.revoked_at is not null then (ce.revoked_at at time zone 'Asia/Kolkata')::date end);
end;
$$;

