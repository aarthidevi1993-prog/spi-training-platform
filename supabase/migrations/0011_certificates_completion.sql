-- Per-batch transaction lock serialising requirement changes,
-- recommendations, approvals, issues and revocations of one batch.
create function public.completion_batch_lock(p_batch_id uuid)
returns void
language sql
volatile
set search_path = ''
as $$
  select pg_advisory_xact_lock(hashtextextended('arsene.completion:' || p_batch_id::text, 0));
$$;

-- Why the batch's requirements are locked (NULL = editable). Reads
-- only; callers that change requirements take the locks first.
create function public.completion_requirements_lock_reason(p_batch_id uuid)
returns text
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_status public.batch_status;
begin
  select b.status into v_status from public.batches b where b.id = p_batch_id;
  if not found then
    return 'batch_not_found';
  elsif v_status = 'completed' then
    return 'batch_completed';
  elsif v_status = 'cancelled' then
    return 'batch_cancelled';
  elsif exists (select 1 from public.completion_records cr where cr.batch_id = p_batch_id and cr.status = 'approved') then
    return 'approvals_exist';
  end if;
  return null;
end;
$$;

-- 20 uppercase hex characters = 80 random bits from gen_random_uuid()
-- (a cryptographically strong source): hex 1–12 and 18–25 of a v4 UUID
-- skip its fixed version (13th) and variant (17th) digits.
create function public.new_verification_code()
returns text
language plpgsql
volatile
set search_path = ''
as $$
declare
  v text := replace(gen_random_uuid()::text, '-', '');
begin
  return upper(substr(v, 1, 12) || substr(v, 18, 8));
end;
$$;

-- Next ARS-SPI-YYYY-NNNNNN (year in India time). The counter row is
-- locked by the UPDATE until the transaction ends, so concurrent issues
-- are serialised and a rollback also rolls the counter back.
create function public.next_certificate_number()
returns text
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  v_year   smallint := extract(year from (now() at time zone 'Asia/Kolkata'))::smallint;
  v_value  integer;
begin
  insert into public.certificate_number_counters (year, last_value) values (v_year, 0)
  on conflict (year) do nothing;

  update public.certificate_number_counters c
     set last_value = c.last_value + 1
   where c.year = v_year and c.last_value < 999999
  returning c.last_value into v_value;

  if v_value is null then
    raise exception 'Certificate numbers for % are exhausted.', v_year using errcode = '54000';
  end if;
  return format('ARS-SPI-%s-%s', v_year, lpad(v_value::text, 6, '0'));
end;
$$;

-- Live completion eligibility of one student in one batch. Read-only.
create function public.completion_eligibility(p_batch_id uuid, p_student_id uuid)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_batch_status   public.batch_status;
  v_enrolment      public.enrollment_status;
  v_enrolled_at    timestamptz;
  v_enrol_date     date;
  v_total          integer := 0;
  v_attended       integer := 0;
  v_att_ok         boolean;
  v_fa             record;
  v_fa_state       text;
  v_fa_passed      boolean;
  v_fa_percentage  numeric;
  v_req            integer := 0;
  v_valid          integer := 0;
  v_done           integer := 0;
  v_req_ids        uuid[] := '{}';
  v_missing_ids    uuid[] := '{}';
  v_invalid_ids    uuid[] := '{}';
  v_as_state       text;
  v_batch_ok       boolean;
  v_enrol_ok       boolean;
begin
  select b.status into v_batch_status from public.batches b where b.id = p_batch_id;
  if not found then
    return jsonb_build_object('eligible', false, 'reason', 'batch_not_found', 'computed_at', now());
  end if;

  select bs.enrollment_status, bs.enrolled_at into v_enrolment, v_enrolled_at
    from public.batch_students bs
   where bs.batch_id = p_batch_id and bs.student_id = p_student_id;
  if not found then
    return jsonb_build_object('eligible', false, 'reason', 'not_enrolled', 'computed_at', now());
  end if;

  v_batch_ok := v_batch_status = 'completed';
  v_enrol_ok := v_enrolment in ('enrolled', 'completed');
  v_enrol_date := (v_enrolled_at at time zone 'Asia/Kolkata')::date;

  -- Attendance: non-cancelled classes of the batch on/after the enrolment
  -- date. Present/late/excused = attended; absent/unmarked = not.
  select count(*)::integer,
         count(*) filter (where ca.status in ('present', 'late', 'excused'))::integer
    into v_total, v_attended
    from public.classes c
    left join public.class_attendance ca on ca.class_id = c.id and ca.student_id = p_student_id
   where c.batch_id = p_batch_id
     and c.status <> 'cancelled'
     and c.class_date >= v_enrol_date;
  -- Exact integer comparison: attended / total >= 75 %.
  v_att_ok := v_total > 0 and v_attended * 4 >= v_total * 3;

  -- Final assessment: the designated test, still valid, effectively
  -- closed (so eligibility never reveals an unreleased result), with a
  -- passed best result.
  select fa.test_id, t.title, t.test_type, t.status, t.available_from, t.available_until, c.status as class_status
    into v_fa
    from public.batch_final_assessments fa
    join public.tests t on t.id = fa.test_id
    join public.classes c on c.id = t.class_id
   where fa.batch_id = p_batch_id;
  if not found then
    v_fa_state := 'not_designated';
  elsif v_fa.test_type <> 'final_exam' or v_fa.status = 'draft' or v_fa.class_status = 'cancelled' then
    v_fa_state := 'requirement_invalid';
  elsif public.test_effective_status(v_fa.status, v_fa.available_from, v_fa.available_until) <> 'closed' then
    v_fa_state := 'pending';
  else
    select br.passed, br.percentage into v_fa_passed, v_fa_percentage
      from public.test_best_results br
     where br.test_id = v_fa.test_id and br.student_id = p_student_id;
    v_fa_state := case when not found then 'not_attempted' when v_fa_passed then 'passed' else 'failed' end;
  end if;

  -- Required assignments: each must still be valid and have a returned,
  -- scored submission.
  select count(*)::integer,
         count(*) filter (where ca.status in ('published', 'closed') and c.status <> 'cancelled')::integer,
         count(*) filter (where ca.status in ('published', 'closed') and c.status <> 'cancelled'
                            and s.status = 'returned' and s.score is not null)::integer,
         coalesce(array_agg(ra.assignment_id order by ra.assignment_id), '{}'),
         coalesce(array_agg(ra.assignment_id order by ra.assignment_id)
                    filter (where ca.status in ('published', 'closed') and c.status <> 'cancelled'
                              and not (s.status is not distinct from 'returned' and s.score is not null)), '{}'),
         coalesce(array_agg(ra.assignment_id order by ra.assignment_id)
                    filter (where not (ca.status in ('published', 'closed') and c.status <> 'cancelled')), '{}')
    into v_req, v_valid, v_done, v_req_ids, v_missing_ids, v_invalid_ids
    from public.batch_required_assignments ra
    join public.class_assignments ca on ca.id = ra.assignment_id
    join public.classes c on c.id = ca.class_id
    left join public.assignment_submissions s on s.assignment_id = ra.assignment_id and s.student_id = p_student_id
   where ra.batch_id = p_batch_id;
  v_as_state := case
    when v_valid < v_req then 'requirement_invalid'
    when v_done = v_req then 'satisfied'
    else 'incomplete'
  end;

  return jsonb_build_object(
    'eligible', v_batch_ok and v_enrol_ok and v_att_ok and v_fa_state = 'passed' and v_as_state = 'satisfied',
    'computed_at', now(),
    'batch_completed', jsonb_build_object('ok', v_batch_ok, 'batch_status', v_batch_status),
    'enrolment', jsonb_build_object('ok', v_enrol_ok, 'enrollment_status', v_enrolment, 'enrolled_on', v_enrol_date),
    'attendance', jsonb_build_object(
      'ok', v_att_ok,
      'attended', v_attended,
      'eligible_classes', v_total,
      'percent', case when v_total > 0 then round(v_attended * 100.0 / v_total, 2) end,
      'minimum_percent', 75),
    'final_assessment', jsonb_build_object(
      'ok', v_fa_state = 'passed',
      'state', v_fa_state,
      'test_id', v_fa.test_id,
      'best_percentage', case when v_fa_state in ('passed', 'failed') then v_fa_percentage end),
    'assignments', jsonb_build_object(
      'ok', v_as_state = 'satisfied',
      'state', v_as_state,
      'required', v_req,
      'satisfied', v_done,
      'assignment_ids', to_jsonb(v_req_ids),
      'missing_ids', to_jsonb(v_missing_ids),
      'invalid_ids', to_jsonb(v_invalid_ids))
  );
end;
$$;

