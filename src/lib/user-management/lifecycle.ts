/** The invitation lifecycle columns read for an invited account — no address, token or Auth data. */
export interface UserInvitationRecord {
  id: string;
  status: string;
  expires_at: string;
  last_sent_at: string | null;
  resend_count: number;
}

/** 0019's resend cap (begin_invitation_delivery) — mirrored only to hide a button the database would refuse. */
export const INVITATION_RESEND_LIMIT = 5;

const INVITATION_STATUSES = new Set(["pending", "accepted", "revoked", "expired"]);

/**
 * The invitation summary the panel shows. A pending invitation past its
 * expiry is shown as expired (the database marks it so on the next
 * attempt). The flags only decide which buttons appear: resend while
 * pending and under the cap (a first send has no cap), revoke while
 * pending. Cooldown is left to the database, which answers with the wait.
 */
export function mapInvitation(r: UserInvitationRecord | null, now: Date = new Date()): UserInvitationSummary | null {
  if (!r || !isUuid(r.id) || !INVITATION_STATUSES.has(r.status)) return null;
  const pastExpiry = !(Date.parse(r.expires_at) > now.getTime());
  const status = (r.status === "pending" && pastExpiry ? "expired" : r.status) as UserInvitationSummary["status"];
  const resendCount = Number.isInteger(r.resend_count) && r.resend_count >= 0 ? r.resend_count : 0;
  const pending = status === "pending";
  return {
    id: r.id,
    status,
    expiresAt: r.expires_at,
    lastSentAt: r.last_sent_at,
    resendCount,
    canResend: pending && (r.last_sent_at === null || resendCount < INVITATION_RESEND_LIMIT),
    canRevoke: pending,
  };
}

/** P5.2 (0029a): invitation_recovery_candidate's answer for one account (lifecycle facts only). */
export interface UserRecoveryCandidateRecord {
  invitation_id: string;
  expires_at: string;
  last_sent_at: string | null;
  resend_count: number;
  recovery_requested_at: string | null;
}

/**
 * A valid candidate → what the panel needs; anything malformed → null (no section). `enabled` is the server-side
 * recovery switch (default off): it only decides whether the panel offers the action.
 */
export function mapRecoveryCandidate(r: UserRecoveryCandidateRecord | null, enabled = false): UserRecoveryCandidate | null {
  if (!r || !isUuid(r.invitation_id) || typeof r.expires_at !== "string") return null;
  return {
    invitationId: r.invitation_id,
    expiresAt: r.expires_at,
    lastSentAt: r.last_sent_at,
    resendCount: Number.isInteger(r.resend_count) && r.resend_count >= 0 ? r.resend_count : 0,
    recoveryRequestedAt: r.recovery_requested_at,
    available: enabled === true,
  };
}

export function mapUserDetail(
  r: UserDetailRecord,
  audit: UserAuditRecord[],
  viewerId: string,
  latestStatusChange: { detail: Json } | null = null,
  invitation: UserInvitationRecord | null = null,
  now: Date = new Date(),
  recoveryCandidate: UserRecoveryCandidateRecord | null = null,
  recoveryEnabled = false,
  /** The account's accepted invitation and the names of its history's actors (Super Admin view only). */
  identity: { record?: UserIdentityRecord | null; actorNames?: ReadonlyMap<string, string> | null } = {}
): UserDetail {
  const accepted = identity.record && identity.record.accepted_user_id === r.id ? identity.record : null;
  const user = mapUserRecord(r, accepted);
  const isSelf = user.id === viewerId;
  // P5.2: only an invited account can recover an invitation; the key is absent otherwise.
  const recovery = user.accountStatus === "invited" ? mapRecoveryCandidate(recoveryCandidate, recoveryEnabled) : null;
  return {
    user,
    isSelf,
    hasStudentRecord: one(r.students) !== null,
    hasTrainerRecord: one(r.trainers) !== null,
    contact: mapContactDetails(r, user),
    history: audit.map((a) => mapAuditRecord(a, viewerId, identity.actorNames ?? null)),
    invitationAcceptedAt: accepted?.accepted_at ?? null,
    actions: actionAvailability(user, isSelf, isNeverActivated(user, latestStatusChange)),
    // Only an invited account has an invitation to manage; anything else shows none.
    invitation: user.accountStatus === "invited" ? mapInvitation(invitation, now) : null,
    ...(recovery ? { recovery } : {}),
  };
}
