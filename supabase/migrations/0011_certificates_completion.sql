end;
$$;

-- Approve (re-checks live eligibility) or reject (note required). Super
-- admin only. Never changes batch_students.
create function public.decide_completion(p_completion_id uuid, p_approve boolean, p_note text default null)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_note     text := nullif(btrim(coalesce(p_note, '')), '');
  r          record;
  v_elig     jsonb;
  v_date     date;
begin
  perform public.require_completion_admin();
  if p_completion_id is null or p_approve is null then
    raise exception 'A completion record and a decision are required.' using errcode = '22023';
  end if;
  if v_note is not null and char_length(v_note) > 1000 then
    return jsonb_build_object('ok', false, 'reason', 'note_too_long');
  end if;
  if not p_approve and v_note is null then
    return jsonb_build_object('ok', false, 'reason', 'note_required');
  end if;

  select cr.batch_id, cr.student_id into r from public.completion_records cr where cr.id = p_completion_id;
  if not found then
    return jsonb_build_object('ok', false, 'reason', 'not_found');
  end if;

  perform public.completion_batch_lock(r.batch_id);
  perform 1 from public.batches b where b.id = r.batch_id for share;
  perform 1 from public.batch_students bs where bs.batch_id = r.batch_id and bs.student_id = r.student_id for share;
  select cr.id, cr.batch_id, cr.student_id, cr.status into r
    from public.completion_records cr where cr.id = p_completion_id for update;
  if r.status <> 'recommended' then
    return jsonb_build_object('ok', false, 'reason', 'not_recommended', 'status', r.status);
  end if;

  if p_approve then
    v_elig := public.completion_eligibility(r.batch_id, r.student_id);
    if (v_elig ->> 'eligible')::boolean is not true then
      return jsonb_build_object('ok', false, 'reason', 'not_eligible', 'eligibility', v_elig);
    end if;
    update public.completion_records
       set status = 'approved', decision_note = v_note   -- the guard stores the evidence and completion_date = batch end_date
     where id = r.id
    returning completion_date into v_date;
    return jsonb_build_object('ok', true, 'status', 'approved', 'completion_date', v_date);
  end if;

  update public.completion_records set status = 'rejected', decision_note = v_note where id = r.id;
  return jsonb_build_object('ok', true, 'status', 'rejected');
end;
$$;

-- Issue (or reissue after revocation) for an approved completion.
create function public.issue_certificate(p_completion_id uuid)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  r        record;
  v_elig   jsonb;
  v_active text;
  c        record;
begin
  perform public.require_completion_admin();
  if p_completion_id is null then
    raise exception 'A completion record is required.' using errcode = '22023';
  end if;

  select cr.batch_id, cr.student_id into r from public.completion_records cr where cr.id = p_completion_id;
  if not found then
    return jsonb_build_object('ok', false, 'reason', 'not_found');
  end if;

  perform public.completion_batch_lock(r.batch_id);
  perform 1 from public.batches b where b.id = r.batch_id for share;
  perform 1 from public.batch_students bs where bs.batch_id = r.batch_id and bs.student_id = r.student_id for share;
  select cr.id, cr.batch_id, cr.student_id, cr.status into r
    from public.completion_records cr where cr.id = p_completion_id for update;
  if r.status <> 'approved' then
    return jsonb_build_object('ok', false, 'reason', 'not_approved', 'status', r.status);
  end if;

  select ce.certificate_number into v_active
    from public.certificates ce
   where ce.batch_id = r.batch_id and ce.student_id = r.student_id and ce.status = 'issued';
  if found then
    return jsonb_build_object('ok', false, 'reason', 'already_issued', 'certificate_number', v_active);
  end if;

  v_elig := public.completion_eligibility(r.batch_id, r.student_id);
  if (v_elig ->> 'eligible')::boolean is not true then
    return jsonb_build_object('ok', false, 'reason', 'not_eligible', 'eligibility', v_elig);
  end if;

  -- The guard generates the number, code, snapshot and hash.
  insert into public.certificates (completion_id, batch_id, student_id)
  values (r.id, r.batch_id, r.student_id)
  returning id, certificate_number, replaces_certificate_id into c;

  return jsonb_build_object('ok', true, 'certificate_id', c.id, 'certificate_number', c.certificate_number,
                            'replaces_certificate_id', c.replaces_certificate_id);
end;
$$;

create function public.revoke_certificate(p_certificate_id uuid, p_reason text)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_reason  text := btrim(coalesce(p_reason, ''));
  v_batch   uuid;
  v_status  public.certificate_status;
  v_number  text;
begin
  perform public.require_completion_admin();
  if p_certificate_id is null then
    raise exception 'A certificate is required.' using errcode = '22023';
  end if;
  if char_length(v_reason) < 10 or char_length(v_reason) > 1000 then
    return jsonb_build_object('ok', false, 'reason', 'invalid_reason');
  end if;

  select ce.batch_id into v_batch from public.certificates ce where ce.id = p_certificate_id;
  if not found then
    return jsonb_build_object('ok', false, 'reason', 'not_found');
  end if;

  perform public.completion_batch_lock(v_batch);
  select ce.status, ce.certificate_number into v_status, v_number
    from public.certificates ce where ce.id = p_certificate_id for update;
  if v_status <> 'issued' then
    return jsonb_build_object('ok', false, 'reason', 'already_revoked');
  end if;

  update public.certificates set status = 'revoked', revocation_reason = v_reason where id = p_certificate_id;
  return jsonb_build_object('ok', true, 'status', 'revoked', 'certificate_number', v_number);
end;
$$;

