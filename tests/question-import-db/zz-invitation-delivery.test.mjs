test("only pending invitations: revoked and accepted are refused; expired is marked expired and never resurrected", async () => {
  const sa = as(W.idv_SA);
  const revoked = await invite(sa);
  await call(sa, "revoke_user_invitation", { p_invitation_id: revoked });
  assert.deepEqual(await begin(sa, revoked), { ok: false, reason: "not_pending", status: "revoked" });

  const email = `${uniq("acc")}@inv.test`;
  const accepted = await invite(sa, { email });
  const uid = await authUser(email);
  // 0029a: unbound → resend_required; bound by a successful send → accepted.
  assert.deepEqual(await call(as(uid), "accept_user_invitation"), { ok: false, reason: "resend_required" });
  await begin(sa, accepted);
  assert.deepEqual(await record(accepted, true, uid), { ok: true, delivery_status: "sent" });
  assert.equal((await call(as(uid), "accept_user_invitation")).ok, true);
  assert.deepEqual(await begin(sa, accepted), { ok: false, reason: "not_pending", status: "accepted" });

  const expiring = await invite(sa);
  await expireNow(expiring);
  assert.deepEqual(await begin(sa, expiring), { ok: false, reason: "expired" });
  assert.equal((await inv(expiring)).status, "expired");
  assert.deepEqual((await events(expiring, "invitation_expired")).map((e) => e.actor), [W.idv_SA]);
  assert.deepEqual(await begin(sa, expiring), { ok: false, reason: "not_pending", status: "expired" });
  assert.equal((await inv(expiring)).last_sent_at, null);
});

test("60-second cooldown between attempts", async () => {
  const sa = as(W.idv_SA);
  const id = await invite(sa);
  assert.equal((await begin(sa, id)).attempt, "initial");
  const r1 = await begin(sa, id);
  assert.equal(r1.reason, "cooldown");
  assert.ok(r1.retry_after_seconds >= 1 && r1.retry_after_seconds <= 60, String(r1.retry_after_seconds));
  await age(id, 30);
  const r2 = await begin(sa, id);
  assert.equal(r2.reason, "cooldown");
  assert.ok(r2.retry_after_seconds >= 25 && r2.retry_after_seconds <= 31, String(r2.retry_after_seconds));
  assert.equal((await inv(id)).resend_count, 0);
  assert.deepEqual(await events(id, "invitation_resent"), []);
  await age(id, 61);
  assert.equal((await begin(sa, id)).attempt, "resend");
});

test("at most 5 resends; each audited as invitation_resent by the caller; expires_at never extended", async () => {
  const sa = as(W.idv_SA);
  const id = await invite(sa);
  const { expires_at } = await inv(id);
  await begin(sa, id);
  for (let k = 1; k <= 5; k++) {
    await age(id, 61);
    const r = await begin(sa, id);
    assert.deepEqual([r.ok, r.attempt, r.resend_count], [true, "resend", k], `resend ${k}`);
    assert.equal(Date.parse(r.expires_at), Date.parse(expires_at));
  }
  await age(id, 61);
  assert.deepEqual(await begin(sa, id), { ok: false, reason: "resend_limit" });
  const row = await inv(id);
  assert.deepEqual([row.resend_count, row.expires_at, row.status], [5, expires_at, "pending"]);
  const resent = await events(id, "invitation_resent");
  assert.deepEqual(resent.map((e) => [e.actor, e.detail.resend_count]), [1, 2, 3, 4, 5].map((k) => [W.idv_SA, k]));
});

