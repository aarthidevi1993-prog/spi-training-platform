-- Refuses any requirement change while the batch's requirements are
-- locked (completed/cancelled batch, or an approved completion exists).
create function public.completion_requirements_assert_unlocked(p_batch_id uuid)
returns void
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  v_reason text;
begin
  perform public.completion_batch_lock(p_batch_id);
  perform 1 from public.batches b where b.id = p_batch_id for share;
  v_reason := public.completion_requirements_lock_reason(p_batch_id);
  if v_reason is not null then
    raise exception 'Completion requirements are locked for this batch.'
      using errcode = '42501', detail = v_reason;
  end if;
end;
$$;
revoke all on function public.completion_requirements_assert_unlocked(uuid) from public, anon, authenticated, service_role;

