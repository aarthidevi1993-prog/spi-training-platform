create function public.set_final_assessment(p_batch_id uuid, p_test_id uuid)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_reason   text;
  t          record;
  v_current  uuid;
begin
  perform public.require_completion_admin();
  if p_batch_id is null or p_test_id is null then
    raise exception 'A batch and a test are required.' using errcode = '22023';
  end if;

  perform public.completion_batch_lock(p_batch_id);
  perform 1 from public.batches b where b.id = p_batch_id for share;
  v_reason := public.completion_requirements_lock_reason(p_batch_id);
  if v_reason = 'batch_not_found' then
    return jsonb_build_object('ok', false, 'reason', 'not_found');
  elsif v_reason is not null then
    return jsonb_build_object('ok', false, 'reason', 'requirements_locked', 'lock_reason', v_reason);
  end if;

  select tt.batch_id, tt.test_type, tt.status, c.status as class_status
    into t
    from public.tests tt join public.classes c on c.id = tt.class_id
   where tt.id = p_test_id;
  if not found or t.batch_id <> p_batch_id then
    return jsonb_build_object('ok', false, 'reason', 'test_not_in_batch');
  elsif t.test_type <> 'final_exam' then
    return jsonb_build_object('ok', false, 'reason', 'not_final_exam');
  elsif t.status = 'draft' then
    return jsonb_build_object('ok', false, 'reason', 'test_draft');
  elsif t.class_status = 'cancelled' then
    return jsonb_build_object('ok', false, 'reason', 'class_cancelled');
  end if;

  select fa.test_id into v_current from public.batch_final_assessments fa where fa.batch_id = p_batch_id for update;
  if v_current = p_test_id then
    return jsonb_build_object('ok', true, 'changed', false);
  elsif v_current is null then
    insert into public.batch_final_assessments (batch_id, test_id) values (p_batch_id, p_test_id);
  else
    update public.batch_final_assessments set test_id = p_test_id where batch_id = p_batch_id;
  end if;
  return jsonb_build_object('ok', true, 'changed', true);
end;
$$;

