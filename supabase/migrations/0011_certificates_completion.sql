-- Completion records: role checks, allowed transitions, stamps, and the
-- eligibility evidence recomputed here (never taken from the writer).
create function public.completion_records_guard()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_elig jsonb;
begin
  if tg_op = 'DELETE' then
    raise exception 'Completion records cannot be deleted.' using errcode = '42501';
  end if;
  if auth.uid() is null then
    raise exception 'Completion records can only be changed by a signed-in user.' using errcode = '42501';
  end if;

  if tg_op = 'UPDATE' then
    if new.id is distinct from old.id or new.batch_id is distinct from old.batch_id
       or new.student_id is distinct from old.student_id or new.created_at is distinct from old.created_at then
      raise exception 'A completion record''s student and batch cannot be changed.' using errcode = '42501';
    end if;
    if old.status = 'approved' then
      raise exception 'An approved completion is final.' using errcode = '42501';
    end if;
    if not ((old.status = 'recommended' and new.status in ('approved', 'rejected', 'withdrawn'))
            or (old.status in ('rejected', 'withdrawn') and new.status = 'recommended')) then
      raise exception 'Invalid completion status change (% to %).', old.status, new.status using errcode = '23514';
    end if;
  elsif new.status <> 'recommended' then
    raise exception 'A completion record must start as recommended.' using errcode = '23514';
  end if;

  perform public.completion_batch_lock(new.batch_id);

  if new.status in ('recommended', 'withdrawn') then
    if not (public.is_super_admin() or public.is_batch_trainer(new.batch_id)) then
      raise exception 'Only a Super Admin or the batch''s trainer can recommend completion.' using errcode = '42501';
    end if;
  elsif not public.is_super_admin() then
    raise exception 'Only a Super Admin can approve or reject completion.' using errcode = '42501';
  end if;

  if new.status = 'recommended' then
    v_elig := public.completion_eligibility(new.batch_id, new.student_id);
    if (v_elig ->> 'eligible')::boolean is not true then
      raise exception 'The student is not eligible for completion.' using errcode = '23514';
    end if;
    new.recommended_by := auth.uid();
    new.recommended_at := now();
    new.eligibility_at_recommendation := v_elig;
    new.decided_by := null;
    new.decided_at := null;
    new.decision_note := null;
    new.eligibility_at_decision := null;
    new.completion_date := null;
  else
    -- Recommendation fields never change after the recommendation.
    new.recommended_by := old.recommended_by;
    new.recommended_at := old.recommended_at;
    new.recommendation_note := old.recommendation_note;
    new.eligibility_at_recommendation := old.eligibility_at_recommendation;
    if new.status = 'withdrawn' then
      new.decided_by := null;
      new.decided_at := null;
      new.decision_note := null;
      new.eligibility_at_decision := null;
      new.completion_date := null;
    else
      new.decided_by := auth.uid();
      new.decided_at := now();
      if new.status = 'approved' then
        v_elig := public.completion_eligibility(new.batch_id, new.student_id);
        if (v_elig ->> 'eligible')::boolean is not true then
          raise exception 'The student is no longer eligible for completion.' using errcode = '23514';
        end if;
        new.eligibility_at_decision := v_elig;
        -- The official completion date is the batch's end date.
        select b.end_date into new.completion_date from public.batches b where b.id = new.batch_id;
      else
        new.eligibility_at_decision := null;
        new.completion_date := null;
      end if;
    end if;
  end if;

  if tg_op = 'INSERT' then
    new.created_at := now();
  end if;
  new.updated_at := now();
  return new;
end;
$$;
revoke all on function public.completion_records_guard() from public, anon, authenticated, service_role;

create trigger completion_records_guard
  before insert or update or delete on public.completion_records
  for each row execute function public.completion_records_guard();

-- Certificates: Super Admin only; the database generates the number,
-- verification code, snapshot and hash on insert (supplied values are
-- ignored); afterwards only issued → revoked is allowed.
create function public.certificates_guard()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_completion  record;
  v_snap        record;
  v_elig        jsonb;
  v_canonical   jsonb;
begin
  if tg_op = 'DELETE' then
    raise exception 'Certificates cannot be deleted. Revoke the certificate instead.' using errcode = '42501';
  end if;
  if auth.uid() is null or not public.is_super_admin() then
    raise exception 'Only a signed-in Super Admin can issue or revoke certificates.' using errcode = '42501';
  end if;

  if tg_op = 'UPDATE' then
    if old.status = 'revoked' then
      raise exception 'A revoked certificate cannot be changed.' using errcode = '42501';
    end if;
    if (new.id, new.certificate_number, new.verification_code, new.completion_id, new.batch_id, new.student_id,
        new.replaces_certificate_id, new.student_name, new.course_code, new.course_title, new.batch_code,
        new.batch_name, new.batch_start_date, new.batch_end_date, new.completion_date, new.trainer_name,
        new.issuer_name, new.template_version, new.signatories, new.snapshot_sha256, new.issued_by, new.issued_at)
       is distinct from
       (old.id, old.certificate_number, old.verification_code, old.completion_id, old.batch_id, old.student_id,
        old.replaces_certificate_id, old.student_name, old.course_code, old.course_title, old.batch_code,
        old.batch_name, old.batch_start_date, old.batch_end_date, old.completion_date, old.trainer_name,
        old.issuer_name, old.template_version, old.signatories, old.snapshot_sha256, old.issued_by, old.issued_at) then
      raise exception 'An issued certificate cannot be changed.' using errcode = '42501';
    end if;
    if new.status <> 'revoked' then
      raise exception 'An issued certificate can only be revoked.' using errcode = '42501';
    end if;
    new.revoked_by := auth.uid();
    new.revoked_at := now();
    new.revocation_reason := btrim(new.revocation_reason);
    return new;
  end if;

  -- INSERT ------------------------------------------------------------
  perform public.completion_batch_lock(new.batch_id);

  select cr.status, cr.batch_id, cr.student_id, cr.completion_date
    into v_completion
    from public.completion_records cr
   where cr.id = new.completion_id;
  if not found or v_completion.batch_id <> new.batch_id or v_completion.student_id <> new.student_id then
    raise exception 'Completion record not found for this certificate.' using errcode = '23503';
  elsif v_completion.status <> 'approved' then
    raise exception 'A certificate can only be issued for an approved completion.' using errcode = '23514';
  end if;

  v_elig := public.completion_eligibility(new.batch_id, new.student_id);
  if (v_elig ->> 'eligible')::boolean is not true then
    raise exception 'The student is no longer eligible for a certificate.' using errcode = '23514';
  end if;

  select s.full_name as student_name, co.course_code, co.title as course_title,
         b.batch_code, b.name as batch_name, b.start_date, b.end_date, tr.full_name as trainer_name
    into v_snap
    from public.batches b
    join public.courses co on co.id = b.course_id
    join public.students s on s.id = new.student_id
    left join public.trainers tr on tr.id = b.trainer_id
   where b.id = new.batch_id;

  new.id                      := gen_random_uuid();
  new.status                  := 'issued';
  new.certificate_number      := public.next_certificate_number();
  new.verification_code       := public.new_verification_code();
  -- Reissue: link the latest revoked, not yet replaced certificate.
  new.replaces_certificate_id := (
    select c.id from public.certificates c
     where c.batch_id = new.batch_id and c.student_id = new.student_id and c.status = 'revoked'
       and not exists (select 1 from public.certificates r where r.replaces_certificate_id = c.id)
     order by c.issued_at desc
     limit 1);
  new.student_name            := v_snap.student_name;
  new.course_code             := v_snap.course_code;
  new.course_title            := v_snap.course_title;
  new.batch_code              := v_snap.batch_code;
  new.batch_name              := v_snap.batch_name;
  new.batch_start_date        := v_snap.start_date;
  new.batch_end_date          := v_snap.end_date;
  new.completion_date         := v_completion.completion_date;
  new.trainer_name            := v_snap.trainer_name;
  new.issuer_name             := 'ARSÈNE Technology Services';
  new.template_version        := 'v1';
  new.signatories             := '[]'::jsonb;
  new.issued_by               := auth.uid();
  new.issued_at               := now();
  new.revoked_by              := null;
  new.revoked_at              := null;
  new.revocation_reason       := null;

  v_canonical := jsonb_build_object(
    'certificate_number', new.certificate_number,
    'student_name', new.student_name,
    'course_code', new.course_code,
    'course_title', new.course_title,
    'batch_code', new.batch_code,
    'batch_name', new.batch_name,
    'batch_start_date', new.batch_start_date,
    'batch_end_date', new.batch_end_date,
    'completion_date', new.completion_date,
    'trainer_name', new.trainer_name,
    'issuer_name', new.issuer_name,
    'template_version', new.template_version,
    'signatories', new.signatories,
    'issued_at', to_char(new.issued_at at time zone 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.US"Z"'));
  new.snapshot_sha256 := encode(sha256(convert_to(v_canonical::text, 'UTF8')), 'hex');
  return new;
end;
$$;
revoke all on function public.certificates_guard() from public, anon, authenticated, service_role;

